#!/usr/bin/env python3
"""Convert a map exported by export_map.cjs into a Luau data module.

Usage: python -I convert_map.py <map.json> <Out.luau>

Encodings (decoded by src/shared/Maps/MapCodec.luau):
  *Rle   base64 of (value:u8, count:u8) pairs, row-major, counts 1..255
  elev4  base64 of 4-bit elevation levels, two cells per byte (low nibble first),
         presentation only (no WarFront rule reads elevation directly).
"""
import base64, json, sys

def rle(values):
    out = bytearray()
    i, n = 0, len(values)
    while i < n:
        v, c = values[i], 1
        while i + c < n and values[i + c] == v and c < 255:
            c += 1
        out += bytes((v, c))
        i += c
    return base64.b64encode(bytes(out)).decode()

def elev4(values):
    lo, hi = min(values), max(values)
    span = (hi - lo) or 1.0
    q = [min(15, int((v - lo) / span * 16)) for v in values]
    if len(q) % 2:
        q.append(0)
    packed = bytes(q[i] | (q[i + 1] << 4) for i in range(0, len(q), 2))
    return base64.b64encode(packed).decode(), lo, hi

def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def lua(v, ind=''):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if v is None:
        return 'nil'
    if isinstance(v, (int, float)):
        return repr(round(v, 4)) if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, dict) and '$typed' in v:
        return lua(v['data'], ind)
    if isinstance(v, list):
        if all(isinstance(x, (int, float)) for x in v):
            return '{' + ', '.join(lua(x) for x in v) + '}'
        inner = ind + '\t'
        return '{\n' + ''.join(f'{inner}{lua(x, inner)},\n' for x in v) + ind + '}'
    if isinstance(v, dict):
        inner = ind + '\t'
        parts = []
        for k, x in v.items():
            key = k if k.isidentifier() else f'[{lua_str(k)}]'
            parts.append(f'{inner}{key} = {lua(x, inner)},\n')
        return '{\n' + ''.join(parts) + ind + '}'
    raise TypeError(type(v))

LEGEND = ["deep", "shallow", "beach", "plains", "forest", "hills", "mountain",
          "snow", "desert", "marsh", "river", "fallout"]

def main(src, dst):
    m = json.load(open(src))
    w, h = m['width'], m['height']
    terrain = m['terrain']['data']
    assert len(terrain) == w * h
    e64, elo, ehi = elev4(m['elev']['data'])
    roads = [{'rank': r['rank'], 'track': bool(r.get('track', False)),
              'pts': [round(p, 2) for p in r['pts']['data']]} for r in m['roads']]
    keep = lambda d, keys: {k: d[k] for k in keys if k in d}
    data = {
        'id': m['id'], 'theme': m['theme'], 'seed': m['seed'],
        'width': w, 'height': h,
        'source': 'WarFront designed map, generated by the original genWorker (tools/conversion/export_map.cjs)',
        'legend': LEGEND,
        'terrainRle': rle(terrain),
        'urbanRle': rle(m['urban']['data']),
        'countryRle': rle(m['country']['data']),
        'elev4': e64, 'elevMin': elo, 'elevMax': ehi,
        'roads': roads,
        'starts': [keep(s, ['x', 'y', 'city']) for s in m['starts']],
        'rigs': [keep(r, ['x', 'y', 'name']) for r in m['rigs']],
        'settlements': [keep(s, ['name', 'x', 'y', 'kind', 'pop', 'port']) for s in m['settlements']],
        'countries': [keep(c, ['name', 'iso', 'slot', 'cells']) for c in m['countries']],
    }
    header = ('--!strict\n-- GENERATED by tools/conversion/convert_map.py. Do not edit by hand.\n'
              '-- Source data is derived from WarFront (rights holder content). Keep the repo private.\n')
    open(dst, 'w', encoding='utf-8').write(header + 'return ' + lua(data) + '\n')
    print(f'{dst}: {w}x{h}, {len(roads)} roads, {len(data["rigs"])} rigs, '
          f'{len(data["settlements"])} settlements, terrainRle {len(data["terrainRle"])} chars')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
