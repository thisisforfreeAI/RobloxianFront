#!/usr/bin/env python3
"""Turn the rules TSV from extract_rules.py into src/shared/GameData/RulesData.luau (git-ignored).
Usage: python -I rules_to_luau.py <rules.tsv> <RulesData.luau>
Keeps the flat dotted keys exactly as WarFront names them (e.g. "units.tank.cost")."""
import sys

def value(s):
    if s in ('true', 'false'):
        return s
    float(s)  # raises on anything that is not a number
    return s

def main(src, dst):
    rows = [l.rstrip('\n').split('\t') for l in open(src, encoding='utf-8') if l.strip()]
    lines = ['--!strict', '-- GENERATED by tools/conversion/rules_to_luau.py from WarFront\'s modding guide.',
             f'-- {len(rows)} rules, default values of WarFront demo 0.1.0. Do not edit by hand.',
             'return {']
    for k, v in rows:
        lines.append(f'\t["{k}"] = {value(v)},')
    lines.append('}')
    open(dst, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{len(rows)} rules -> {dst}')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
