#!/usr/bin/env python3
"""Write the WarFront unit catalog and locked engine constants as Luau data.

Usage: python -I extract_catalog.py <dist_dir> <GameData_dir>
  <dist_dir>     the extracted app.asar's dist/ folder
  <GameData_dir> src/shared/GameData (git-ignored)

Outputs:
  UnitCatalog.luau  names, factories, locomotion, weapon, armour class per base unit,
                    from the modding guide table "What you can base a unit on".
  Locked.luau       rules mods may not change (absent from the rules table), read from
                    the game bundle: match.tickHz, match.cellScale.
"""
import glob, html, os, re, sys

MADE_AT = {"Headquarters": "hq", "Barracks": "barracks", "War Factory": "factory",
           "the capital only": "capital", "the harbour": "navalyard"}

def cells_of(row):
    return [html.unescape(re.sub(r"<[^>]+>", "", c)).strip()
            for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", row, flags=re.S)]

def unit_table(guide):
    start = guide.find("What you can base a unit on")
    end = guide.find("Every word a unit may have", start)
    rows = re.findall(r"<tr[^>]*>(.*?)</tr>", guide[start:end], flags=re.S)
    units = {}
    for r in rows:
        c = cells_of(r)
        if len(c) != 11 or c[0] == "like":
            continue
        like, name, made, moves, *_rest = c
        weapon, armour = c[9], c[10]
        made_at = [MADE_AT.get(p.strip(), p.strip()) for p in made.split(",")]
        units[like] = {"name": name, "madeAt": made_at, "moves": moves, "weapon": weapon,
                       "armour": armour, "source": "modding guide table"}
    return units

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main(dist, out_dir):
    guide = open(os.path.join(dist, "modding-guide.html"), encoding="utf-8").read()
    units = unit_table(guide)
    if len(units) < 13:
        sys.exit(f"expected 13 base units in the guide table, found {len(units)}")
    # The Mortar Team is listed among the Barracks' products but has no row of its own.
    if "mortar" not in units and "Mortar Team" in guide:
        units["mortar"] = {"name": "Mortar Team", "madeAt": ["barracks"], "moves": "foot",
                           "weapon": "shell", "armour": "soft",
                           "source": "INFERRED: no guide row; moves/weapon/armour assumed"}
    os.makedirs(out_dir, exist_ok=True)
    lines = ["--!strict", "-- GENERATED by tools/conversion/extract_catalog.py. WarFront-derived: git-ignored.",
             "return {"]
    for uid in sorted(units):
        u = units[uid]
        made = ", ".join(lua_str(m) for m in u["madeAt"])
        lines.append(f"\t{uid} = {{ name = {lua_str(u['name'])}, madeAt = {{ {made} }}, moves = {lua_str(u['moves'])}, "
                     f"weapon = {lua_str(u['weapon'])}, armour = {lua_str(u['armour'])}, source = {lua_str(u['source'])} }},")
    lines.append("}")
    open(os.path.join(out_dir, "UnitCatalog.luau"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

    bundle = glob.glob(os.path.join(dist, "assets", "main-*.js"))
    if len(bundle) != 1:
        sys.exit(f"expected one main bundle, found {bundle}")
    js = open(bundle[0], encoding="utf-8").read()
    locked = {}
    for key in ("tickHz", "cellScale"):
        m = re.search(key + r":(\d+(?:\.\d+)?)", js)
        if not m:
            sys.exit(f"locked constant {key} not found in bundle")
        locked["match." + key] = m.group(1)
    body = "\n".join(f'\t["{k}"] = {v},' for k, v in locked.items())
    open(os.path.join(out_dir, "Locked.luau"), "w", encoding="utf-8").write(
        "--!strict\n-- GENERATED by tools/conversion/extract_catalog.py from the game bundle. Git-ignored.\n"
        "-- Rules mods may not change, so they are absent from the rules table.\nreturn {\n" + body + "\n}\n")
    print(f"{len(units)} units, locked {locked} -> {out_dir}")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
