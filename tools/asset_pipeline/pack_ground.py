"""Pack the game's baked ground (tools/conversion/export_ground.cjs output) into a local Luau module.

The ground is the game's "fine" ground texture, 3 px a map cell. It is cut into upright strips no
wider than 1024 px (the EditableImage limit) and each strip is stored raw DEFLATE + base64 in
src/client/DevAssets/Ground_<id>.luau (git-ignored: it is the game's art). MapRenderer draws it in
place of the placeholder 1 px a cell terrain colours. Pixels are unchanged; the shader's per-pixel
work on top of it (forest floor, water, light) is not reproduced.

Usage: python tools/asset_pipeline/pack_ground.py <map id> <ground.rgba> <width> <height>
"""
import base64
import os
import sys
import zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "client", "DevAssets")
MAX = 1024


def main():
    mid, path, w, h = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])
    raw = open(path, "rb").read()
    if len(raw) != w * h * 4:
        raise SystemExit(f"{path}: {len(raw)} bytes, expected {w * h * 4}")
    if h > MAX:
        raise SystemExit(f"height {h} is over {MAX}; cut rows too")
    n = -(-w // MAX)
    step = -(-w // n)
    pieces = []
    for x0 in range(0, w, step):
        pw = min(step, w - x0)
        rows = b"".join(raw[(y * w + x0) * 4:(y * w + x0 + pw) * 4] for y in range(h))
        c = zlib.compressobj(9, zlib.DEFLATED, -15)
        pieces.append((x0, pw, base64.b64encode(c.compress(rows) + c.flush()).decode()))
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, f"Ground_{mid}.luau"), "w", newline="\n") as f:
        f.write("--!strict\n-- GENERATED by tools/asset_pipeline/pack_ground.py from the game's ground baker. Local only (git-ignored).\n")
        f.write(f'return {{\n\tid = "{mid}", width = {w}, height = {h}, pieces = {{\n')
        for x0, pw, data in pieces:
            f.write(f'\t\t{{ x = {x0}, width = {pw}, deflate = "{data}" }},\n')
        f.write("\t},\n}\n")
    print(f"Ground_{mid}: {w}x{h} px, {len(pieces)} pieces, {sum(len(p[2]) for p in pieces) // 1024} KB")


if __name__ == "__main__":
    main()
