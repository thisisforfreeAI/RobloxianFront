"""Pack the street lamp spots of a designed map's baked towns for StreetFurnitureRenderer.

Where the spots come from (traced, see docs/private/STREET_FURNITURE_TRACE.md): the game's town
generator marks each street lamp as one texel with surface code 201 (the .city atlas alpha), coloured
like the street, so it cannot be seen by day; at night the ground shader lights it. This tool finds
every code-201 texel and the way into the street from it, so the port can stand a post there.

PORT ADDITION: the game draws no lamp post. The post, its art, its height and shadow are this port's
own; only the spot is the game's. The arm's direction is worked out here from the street texels
round the spot: toward the lamp's own asphalt colour (APPROX: the game never needs one).

Writes, git-ignored (it is derived from the original towns):
  src/client/DevAssets/StreetFurniture_<id>.luau
    return { id, cellPx, lamps = { x, y, angle, ... } }
    x, y: the lamp texel's centre in map cells; angle: radians, the way from the post's foot to the
    lamp head, in map axes (x east, y south).

Usage:
  python tools/asset_pipeline/pack_street_furniture.py <dist/cities/<id>.city> [output.luau]
"""
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pack_city import read_city, map_size  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "client", "DevAssets")

LAMP = 201  # the .city atlas alpha code for a lamp texel (traced)
STREET = 200  # the code for a street texel (traced)
REACH = 6  # texels looked at round a lamp to find the way into the street (port choice)
LIKE = 30  # how close (sum of |r|,|g|,|b|) a texel's colour is to the lamp's to count as the same asphalt


def world_rgba(head, parts, w, h):
    """The towns' baked texels over the whole map (RGBA, alpha = surface code), from the atlas and index."""
    size = head["size"]
    index = np.frombuffer(parts["index"], np.uint8).reshape(h, w, 4).astype(np.int64)
    ids = index[:, :, 0] + (index[:, :, 1] << 8) + (index[:, :, 2] << 16)
    atlas = np.frombuffer(parts["atlas"], np.uint8).reshape(head["atlasH"], head["atlasW"], 4)
    out = np.zeros((h * size, w * size, 4), np.uint8)
    for y, x in zip(*np.where(ids > 0)):
        tile = int(ids[y, x] - 1)
        tx, ty = (tile % head["perRow"]) * size, (tile // head["perRow"]) * size
        out[y * size:(y + 1) * size, x * size:(x + 1) * size] = atlas[ty:ty + size, tx:tx + size]
    return out


def lamp_spots(codes, rgb=None, reach=REACH):
    """Each lamp texel as (tx, ty, angle): angle points from the kerb into the street.

    The game puts a lamp on the outermost texel of a street's asphalt. With the texels' colours, the
    way in is toward the texels round it of the lamp's own asphalt colour (the kerb, pavements and
    squares, also street-coded, are paler); without them, toward all street texels.
    """
    h, w = codes.shape
    road = (codes == STREET) | (codes == LAMP)
    out = []
    for ty, tx in zip(*np.where(codes == LAMP)):
        x0, x1 = max(0, tx - reach), min(w, tx + reach + 1)
        y0, y1 = max(0, ty - reach), min(h, ty + reach + 1)
        mask = road[y0:y1, x0:x1]
        if rgb is not None:
            own = rgb[ty, tx, :3].astype(np.int32)
            mask = mask & (np.abs(rgb[y0:y1, x0:x1, :3].astype(np.int32) - own).sum(-1) <= LIKE)
        ys, xs = np.nonzero(mask)
        dx = xs + x0 - tx
        dy = ys + y0 - ty
        keep = dx * dx + dy * dy <= reach * reach
        mx, my = float(dx[keep].sum()), float(dy[keep].sum())
        if mx * mx + my * my < 1e-9:
            angle = -math.pi / 2  # APPROX: a lamp with the street even all round faces north
        else:
            angle = math.atan2(my, mx)
        out.append((int(tx), int(ty), angle))
    out.sort(key=lambda s: (s[1], s[0]))
    return out


def write(path, map_id, size, spots):
    rows = []
    for tx, ty, a in spots:
        rows.append(f"{(tx + 0.5) / size:.4f}, {(ty + 0.5) / size:.4f}, {a:.3f},")
    body = "\n\t\t".join(rows)
    text = (
        "--!strict\n"
        "-- GENERATED by tools/asset_pipeline/pack_street_furniture.py. Local only (git-ignored).\n"
        "-- lamps: x, y (cells, the lamp texel's centre), angle (radians, foot to head), repeated.\n"
        "return {\n"
        f'\tid = "{map_id}", cellPx = {size},\n'
        "\tlamps = {\n"
        f"\t\t{body}\n"
        "\t},\n"
        "}\n"
    )
    with open(path, "w", newline="\n") as f:
        f.write(text)


def main(argv):
    if not argv:
        raise SystemExit(__doc__)
    head, parts = read_city(argv[0])
    w, h = map_size(head["key"])
    rgba = world_rgba(head, parts, w, h)
    spots = lamp_spots(rgba[:, :, 3], rgba)
    out = argv[1] if len(argv) > 1 else os.path.join(OUT, f"StreetFurniture_{head['id']}.luau")
    write(out, head["id"], head["size"], spots)
    print(f"{head['id']}: {len(spots)} lamp spots -> {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
